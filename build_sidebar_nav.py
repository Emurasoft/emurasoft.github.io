"""Move the current section's sidebar branch out of every page.

Sphinx renders the current section's expanded branch into the sidebar of every
page. Except for the ``current`` markers, that branch is identical for every
page in the section, so it is repeated thousands of times. This script:

* extracts the branch from each page and stores one canonical copy per section
  in ``_static/nav.js``;
* removes the branch from each page, leaving the top-level links inline.

The page's ``scripts.js`` inserts the stored branch when it loads, and restores
the ``current`` markers. Hrefs in the stored data are prefixed with
``{{ROOT}}`` and are made relative to the language root, so the same data
works online and in the local Help.

Only the extracted branch is removed. The rest of each document is preserved
byte for byte.

Usage: python build_sidebar_nav.py <directory>
"""

import json
import posixpath
import re
import sys
from collections import Counter
from pathlib import Path

ROOT_MARKER = '{{ROOT}}'
NAV_FILE = Path('_static') / 'nav.js'
NAV_PREFIX = '// Generated by build_sidebar_nav.py. Do not edit.\nwindow.SIDEBAR_NAV='

SIDEBAR = b'class="sphinxsidebar"'
WRAPPER = b'class="sphinxsidebarwrapper"'

# Start tags. Quoted attribute values may contain ">".
START_TAG = re.compile(rb"""<(?:li|a|ul)\b(?:[^>"']|"[^"]*"|'[^']*')*>""")
ANCHOR_TAG = re.compile(rb"""<a\b(?:[^>"']|"[^"]*"|'[^']*')*>""")
CLASS_ATTRIBUTE = re.compile(rb'\sclass="([^"]*)"')
HREF_ATTRIBUTE = re.compile(rb'\shref="([^"]*)"')
LIST_TAG = re.compile(rb'<ul\b|</ul>')

ABSOLUTE_HREF = re.compile(r'^(?:[A-Za-z][A-Za-z0-9+.-]*:|//|/)')


class SliceError(Exception):
    """The sidebar of a page does not have the expected structure."""


def resolve_path(page_path: str, href: str) -> str:
    """Resolve a sidebar href to a path relative to the build root."""
    if href.startswith('#'):
        return page_path + href[1:]
    if ABSOLUTE_HREF.match(href):
        raise SliceError(f'absolute href in the sidebar: {href}')

    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(page_path), href))
    if resolved.startswith('..'):
        raise SliceError(f'href leaves the build directory: {href}')
    return resolved


def find_sidebar(html: bytes) -> tuple[int, int]:
    """Return the offsets of the sidebar region, or (-1, -1) if there is none."""
    sidebar = html.find(SIDEBAR)
    if sidebar < 0:
        return -1, -1

    end = html.find(b'class="document"', sidebar)
    if end < 0:
        end = len(html)
    return sidebar, end


def find_current_item(html: bytes, sidebar: int, end: int) -> tuple[int, int] | None:
    """Return the start and end offsets of the current top-level item."""
    if html.find(WRAPPER, sidebar, end) < 0:
        raise SliceError('the sidebar wrapper was not found')

    found = None
    for tag in START_TAG.finditer(html, sidebar, end):
        class_match = CLASS_ATTRIBUTE.search(tag.group(0))
        if not class_match:
            continue
        tokens = class_match.group(1).split()
        if b'toctree-l1' in tokens and b'current' in tokens:
            if found is not None:
                raise SliceError('more than one current top-level item')
            found = (tag.start(), tag.end())

    return found


def extract_branch(html: bytes, item_end: int, end: int) -> tuple[int, int]:
    """Return the offsets of the branch list of a top-level item."""
    list_start = html.find(b'<ul', item_end, end)
    if list_start < 0:
        return item_end, item_end

    # A top-level item without a branch has no list before its closing tag.
    item_close = html.find(b'</li>', item_end, end)
    if item_close < 0:
        raise SliceError('the current item is not closed')
    if list_start > item_close:
        return item_end, item_end

    depth = 0
    for tag in LIST_TAG.finditer(html, list_start, end):
        if tag.group(0) == b'</ul>':
            depth -= 1
            if depth == 0:
                return list_start, tag.end()
        else:
            depth += 1
    raise SliceError('the branch list is not closed')


def canonicalize(branch: bytes, page_path: str) -> bytes:
    """Make one branch byte-identical across all pages of its section."""

    def fix_tag(tag_match: re.Match[bytes]) -> bytes:
        tag = tag_match.group(0)

        def fix_class(class_match: re.Match[bytes]) -> bytes:
            tokens = class_match.group(1).split()
            kept = [token for token in tokens if token != b'current']
            if len(kept) == len(tokens):
                return class_match.group(0)
            if not kept:
                return b''
            return b' class="' + b' '.join(kept) + b'"'

        tag = CLASS_ATTRIBUTE.sub(fix_class, tag)

        def fix_href(href_match: re.Match[bytes]) -> bytes:
            href = href_match.group(1).decode('utf-8')
            if ABSOLUTE_HREF.match(href):
                return href_match.group(0)
            target = resolve_path(page_path, href)
            return b' href="' + ROOT_MARKER.encode() + target.encode('utf-8') + b'"'

        return HREF_ATTRIBUTE.sub(fix_href, tag)

    return START_TAG.sub(fix_tag, branch)


def load_existing_nav(build_directory: Path) -> tuple[dict[str, str], dict[str, str]]:
    """Return the sections and pages of an existing nav.js, if there is one."""
    path = build_directory / NAV_FILE
    if not path.is_file():
        return {}, {}

    try:
        text = path.read_text(encoding='utf-8')
        start = text.index('{', text.index('SIDEBAR_NAV'))
        data = json.loads(text[start:].strip().removesuffix(';'))
        return dict(data['sections']), dict(data['pages'])
    except (OSError, UnicodeDecodeError, ValueError, KeyError, TypeError) as error:
        raise SliceError(
            f'cannot read the existing {path}: {error}. '
            f'Delete {build_directory} and build again.'
        )


def scan(directory: Path) -> tuple[list[tuple[Path, int, int, bytes, bytes, str]], dict[str, Counter], int]:
    """Collect every page's branch and the section it belongs to."""
    records = []
    section_branches: dict[str, Counter] = {}
    scanned = 0

    for path in sorted(directory.rglob('*.html')):
        scanned += 1
        data = path.read_bytes()
        page_path = path.relative_to(directory).as_posix()

        try:
            sidebar, region_end = find_sidebar(data)
            if sidebar < 0:
                continue

            item = find_current_item(data, sidebar, region_end)
            if item is None:
                continue

            item_end = item[1]
            link = ANCHOR_TAG.search(data, item_end, region_end)
            if not link:
                raise SliceError('the current item has no link')
            href_match = HREF_ATTRIBUTE.search(link.group(0))
            if not href_match:
                raise SliceError('the current item link has no href')

            section_key = resolve_path(page_path, href_match.group(1).decode('utf-8'))

            start, end = extract_branch(data, item_end, region_end)
            if start == end:
                continue

            raw = data[start:end]
            branch = canonicalize(raw, page_path)
        except SliceError as error:
            raise SliceError(f'{path}: {error}')

        records.append((path, start, end, raw, branch, section_key))
        section_branches.setdefault(section_key, Counter())[branch] += 1

    return records, section_branches, scanned


def write_nav(build_directory: Path, sections: dict[str, str], pages: dict[str, str]) -> int:
    """Write the shared navigation data and return its size in bytes."""
    data = {'sections': sections, 'pages': pages}
    text = NAV_PREFIX + json.dumps(
        data, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + ';\n'
    content = text.encode('utf-8')

    path = build_directory / NAV_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    return len(content)


def process(directory: Path) -> tuple[int, int, int, int, int, int]:
    """Rewrite every page and the shared navigation data.

    Returns the number of files scanned, files rewritten, sections, page
    overrides, bytes removed, and the size of nav.js.
    """
    sections, pages = load_existing_nav(directory)
    records, section_branches, scanned = scan(directory)

    if not scanned:
        raise SliceError(f'no HTML files under {directory}')

    defaults = {}
    for section_key, branches in section_branches.items():
        defaults[section_key] = branches.most_common(1)[0][0]
        sections[section_key] = defaults[section_key].decode('utf-8')

    removed = 0
    for path, start, end, raw, branch, section_key in records:
        page_path = path.relative_to(directory).as_posix()
        if branch == defaults[section_key]:
            pages.pop(page_path, None)
        else:
            pages[page_path] = branch.decode('utf-8')

        data = path.read_bytes()
        if data[start:end] != raw:
            raise SliceError(f'{path}: the page changed while it was processed')
        path.write_bytes(data[:start] + data[end:])
        removed += end - start

    nav_size = write_nav(directory, sections, pages)
    return scanned, len(records), len(sections), len(pages), removed, nav_size


def main() -> int:
    if len(sys.argv) != 2:
        print('usage: python build_sidebar_nav.py <directory>', file=sys.stderr)
        return 2

    directory = Path(sys.argv[1])
    if not directory.is_dir():
        print(f'build_sidebar_nav: not a directory: {directory}', file=sys.stderr)
        return 2

    try:
        scanned, rewrote, sections, overrides, removed, nav_size = process(directory)
    except (OSError, SliceError) as error:
        print(f'build_sidebar_nav: {error}', file=sys.stderr)
        return 1

    print(
        f'build_sidebar_nav: scanned {scanned} files, rewrote {rewrote}, '
        f'{sections} sections, {overrides} page overrides, '
        f'removed {removed} bytes, wrote nav.js ({nav_size} bytes)'
    )
    return 0


if __name__ == '__main__':
    sys.exit(main())
